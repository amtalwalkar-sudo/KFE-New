import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const store = read('android/app/src/main/java/com/kanishka/pwa/KfeCanonicalWorkStore.java')
const plugin = read('android/app/src/main/java/com/kanishka/pwa/KfeCanonicalWorkPlugin.java')
const bridge = read('src/infrastructure/android/nativeCanonicalWork.js')
const boundary = read('src/application/work/canonicalWorkBoundary.js')
const indexedDb = read('src/utils/indexedDB.js')
const version = read('src/constants/canonicalDatabase.js')
const ports = read('src/application/work/workRuntimePorts.js')
const adapter = read('src/infrastructure/work/workRuntimeAdapter.js')
const activity = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const overlayService = read('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java')

assert.match(store, /CREATE TABLE canonical_records/)
assert.match(boundary, /BrowserCanonicalWorkService\.putRecord/)
assert.match(boundary, /WorkRuntimePorts\.canonicalWork\.isAvailable\(\)/)
assert.match(read('src/infrastructure/work/browserCanonicalWork.js'), /STORE_BY_ENTITY/)
assert.match(indexedDb, /createSimpleStore\(db, 'canonical_operations'/)
assert.match(version, /CANONICAL_DB_VERSION = 16/)
assert.match(store, /CREATE TABLE canonical_operations/)
assert.match(store, /CREATE TABLE canonical_audit/)
assert.match(store, /db\.beginTransaction\(\)/)
assert.match(store, /db\.setTransactionSuccessful\(\)/)
assert.match(store, /operation_id TEXT PRIMARY KEY/)
assert.match(store, /operationId was already used for a different command/)
assert.match(store, /operationId was already used with a different payload/)
assert.match(store, /jsonEquivalent\(priorRecord, record\)/, 'idempotent retries must reject operation-ID reuse for a different payload')
assert.match(store, /Stale canonical write rejected/)
assert.match(store, /different payloads share updatedAt/)
assert.match(overlayService, /!trip\.has\(key\)&&!candidate\.isNull\(key\)\)trip\.put\(key,candidate\.get\(key\)\)/, 'A stale persisted PWA snapshot may fill absent canonical fields but must not overwrite existing values or explicit nulls owned by native canonical storage.')
assert.match(read('src/application/work/workService.js'), /recoverCanonicalWorkSnapshot/)
assert.match(store, /db\.insertOrThrow\("canonical_audit"/)
assert.match(plugin, /@CapacitorPlugin\(name = "KfeCanonicalWork"\)/)
for (const method of ['putRecord', 'getRecord', 'listRecords', 'getOperation']) assert.ok(plugin.includes('public void ' + method + '('), 'Missing plugin method: ' + method)
for (const method of ['putRecord', 'getRecord', 'listRecords', 'getOperation']) assert.ok(bridge.includes('async ' + method + '('), 'Missing bridge method: ' + method)
assert.match(ports, /canonicalWork: \['putRecord', 'getRecord', 'listRecords', 'getOperation', 'isAvailable'\]/)
assert.match(adapter, /canonicalWork: NativeCanonicalWorkService/)
assert.match(activity, /registerPlugin\(KfeCanonicalWorkPlugin\.class\)/)
console.log('PASS: native canonical persistence boundary contract')
