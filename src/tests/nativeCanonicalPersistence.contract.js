import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const store = read('android/app/src/main/java/com/kanishka/pwa/KfeCanonicalWorkStore.java')
const plugin = read('android/app/src/main/java/com/kanishka/pwa/KfeCanonicalWorkPlugin.java')
const bridge = read('src/infrastructure/android/nativeCanonicalWork.js')
const boundary = read('src/application/work/canonicalWorkBoundary.js')
const indexedDb = read('src/utils/indexedDB.js')
const browserCanonical = read('src/infrastructure/work/browserCanonicalWork.js')
const version = read('src/constants/canonicalDatabase.js')
const ports = read('src/application/work/workRuntimePorts.js')
const adapter = read('src/infrastructure/work/workRuntimeAdapter.js')
const activity = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const overlayService = read('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java')

assert.match(browserCanonical, /previous\.outcome\?\.record/)
assert.match(browserCanonical, /jsonEquivalent\(previous\.outcome\.record, record\)/, 'Browser idempotent replay must reject a reused operation ID with a different record payload.')
assert.match(browserCanonical, /operationId was already used with a different payload/)
assert.match(store, /CREATE TABLE canonical_records/)
assert.ok(store.includes('synchronized Outcome persistTripBoundarySnapshot(String operationId, String tripId'))
assert.ok(store.includes('SAVE_TRIP_BOUNDARY_SNAPSHOT'))
assert.ok(overlayService.includes('persistTripBoundarySnapshot(operationId,tripId,field,snapshot)'))
assert.ok(!overlayService.includes('store.putRecord("native-trip-location-'), 'Boundary GPS must not rewrite a stale full-trip payload.')
const boundarySnapshotWriter = store.slice(store.indexOf('synchronized Outcome persistTripBoundarySnapshot'), store.indexOf('Commits a native overlay fare/cancellation'))
assert.ok(!boundarySnapshotWriter.includes('trip.put("updatedAt"'), 'Optional GPS metadata must not advance the trip business version.')

assert.match(boundary, /BrowserCanonicalWorkService\.putRecord/)
assert.match(boundary, /async persistTripBoundarySnapshot\(input\)/, 'The application boundary must expose the dedicated atomic GPS metadata operation.')
assert.match(boundary, /WorkRuntimePorts\.canonicalWork\.isAvailable\(\)/)
assert.match(read('src/infrastructure/work/browserCanonicalWork.js'), /STORE_BY_ENTITY/)
assert.match(indexedDb, /createSimpleStore\(db, 'canonical_operations'/)
assert.match(version, /CANONICAL_DB_VERSION = 16/)
assert.match(store, /CREATE TABLE canonical_operations/)
assert.match(store, /CREATE TABLE canonical_audit/)
assert.match(store, /db\.beginTransaction\(\)/)
assert.match(store, /db\.setTransactionSuccessful\(\)/)
assert.match(store, /operation_id TEXT PRIMARY KEY/)
assert.match(store, /operationId was already used for a different command/)
assert.match(store, /operationId was already used with a different payload/)
assert.match(store, /jsonEquivalent\(priorRecord, record\)/, 'idempotent retries must reject operation-ID reuse for a different payload')
assert.ok(store.includes('boolean sameRecord = priorRecord != null'))
assert.ok(store.includes('withoutTripBoundarySnapshots(priorRecord)'))
const replayPayloadGuard = store.indexOf('boolean sameRecord = priorRecord != null')
const replayCommitAcknowledgement = store.indexOf('db.setTransactionSuccessful();', replayPayloadGuard)
assert.ok(replayPayloadGuard >= 0 && replayCommitAcknowledgement > replayPayloadGuard, 'business-payload mismatch must be rejected before an idempotent replay is acknowledged')
assert.match(store, /Stale canonical write rejected/)
assert.match(store, /different payloads share updatedAt/)
assert.match(overlayService, /!trip\.has\(key\)&&!candidate\.isNull\(key\)\)trip\.put\(key,candidate\.get\(key\)\)/, 'A stale persisted PWA snapshot may fill absent canonical fields but must not overwrite existing values or explicit nulls owned by native canonical storage.')
assert.match(read('src/application/work/workService.js'), /recoverCanonicalWorkSnapshot/)
assert.match(store, /db\.insertOrThrow\("canonical_audit"/)
const recordWriteIndex = store.indexOf('db.insertWithOnConflict("canonical_records"')
const operationWriteIndex = store.indexOf('db.insertOrThrow("canonical_operations"')
const auditWriteIndex = store.indexOf('db.insertOrThrow("canonical_audit"')
const transactionCommitIndex = store.indexOf('db.setTransactionSuccessful();', auditWriteIndex)
assert.ok(recordWriteIndex >= 0 && operationWriteIndex > recordWriteIndex && auditWriteIndex > operationWriteIndex && transactionCommitIndex > auditWriteIndex, 'record, idempotency outcome and audit must commit in one ordered SQLite transaction')
assert.ok(overlayService.includes('createdAtMillis(eventId)'), 'native lifecycle retries must derive timestamps from the durable outbox event')
assert.ok(overlayService.includes('native-trip-stage-"+eventId'), 'each durable lifecycle event must have its own canonical operation ID')
assert.ok(overlayService.includes('trip.put("updatedAt",eventTimestamp)'), 'lifecycle retry payload must preserve its original version timestamp');
assert.ok(overlayService.includes('persistCanonicalTripForm("FARE",actionTripId,payload,eventId)'), 'fare canonical writes must use the durable outbox event ID');
assert.ok(overlayService.includes('persistCanonicalTripForm("CANCEL",pendingTripId,input,eventId)'), 'cancellation canonical writes must use the durable outbox event ID');
assert.ok(overlayService.includes('native-form-"+mode+"-"+eventId'), 'form retries must be idempotent per durable event, not per trip');
assert.ok(read('android/app/src/main/java/com/kanishka/pwa/KfeNativeEventStore.java').includes('synchronized long createdAtMillis(String id)'), 'event store must expose the persisted timestamp for a lifecycle event')
assert.match(plugin, /@CapacitorPlugin\(name = "KfeCanonicalWork"\)/)
for (const method of ['putRecord', 'persistTripBoundarySnapshot', 'updateTripBoundaryPlaceName', 'getRecord', 'listRecords', 'getOperation']) assert.ok(plugin.includes('public void ' + method + '('), 'Missing plugin method: ' + method)
for (const method of ['putRecord', 'persistTripBoundarySnapshot', 'updateTripBoundaryPlaceName', 'getRecord', 'listRecords', 'getOperation']) assert.ok(bridge.includes('async ' + method + '('), 'Missing bridge method: ' + method)
assert.match(ports, /canonicalWork: \['putRecord', 'persistTripBoundarySnapshot', 'updateTripBoundaryPlaceName', 'getRecord', 'listRecords', 'getOperation', 'isAvailable'\]/)
assert.match(adapter, /canonicalWork: NativeCanonicalWorkService/)
assert.match(activity, /registerPlugin\(KfeCanonicalWorkPlugin\.class\)/)
console.log('PASS: native canonical persistence boundary contract')
