import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = path => fs.readFileSync(path, 'utf8')
const timeline = read('src/views/ActivityTimelineView.vue')
const timelineService = read('src/application/timeline/activityTimelineReadService.js')
const performance = read('src/application/performance/phaseOnePerformanceService.js')
const performanceOverview = read('src/domain/performance/phaseOneOverview.js')
const performanceView = read('src/views/PerformanceView.vue')
const work = read('src/views/WorkModuleView.vue')
const rules = read('KFE_BUSINESS_RULES_REGISTER.md')

assert.match(timeline, /ActivityTimelineReadService\.getTimeline/)
assert.match(timeline, /refreshLocationNames/)
assert.match(timeline, /@touchstart\.passive="onTouchStart"/)
assert.match(timeline, /@touchend\.passive="onTouchEnd"/)
assert.match(timelineService, /getCachedLocationName/)
assert.doesNotMatch(timelineService, /resolveLocationName|reverseGeocod|navigator\.onLine|fetch\s*\(/, 'Timeline read service must not perform implicit network lookups')
assert.match(rules, /manual-only/)
assert.match(rules, /No automatic retries, polling, background connectivity checks/)
assert.match(rules, /Location unavailable/)
assert.match(rules, /Do not calculate ride-distance metrics/)
assert.doesNotMatch(timeline, /businessKm|deadKm|vehicleKm|tripKm|toll|parking/, 'Timeline must not show ride-distance or unrelated expense calculations')

assert.match(performance, /PerformanceRepository\.getSnapshot\(\)/)
assert.match(performance, /calculateFuelPeriodSummary/)
assert.match(performance, /derivePhaseOnePerformanceOverview\(source, effectiveRange/)
assert.match(performanceOverview, /recordedRevenue - fuelSpending/)
assert.doesNotMatch(performance, /DriverTargetService|deriveOperatingKmForecast|deriveFinanceAwarePerformance|deriveFinancialFactModel|breakEvenInputs/)
assert.doesNotMatch(performanceView, /provisionBalances|amortization|break-even|forecast|driver target/i)
assert.match(performanceView, /overview\.incomeAfterFuel/)
assert.match(performanceView, /overview\.fuelCostPerKm/)

assert.doesNotMatch(work, /TODAY'S TARGET|targetProgress|targetValue|PerformanceService/)
assert.doesNotMatch(work, /ShiftReconciliationModal|handleFinalCommit|shiftRevenue|reviewRevenue/, 'End Shift must not expose a separate revenue reconciliation workflow')
console.log('Timeline and basic Performance contracts: PASS')
