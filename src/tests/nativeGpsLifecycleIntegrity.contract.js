import assert from 'node:assert/strict'
import fs from 'node:fs'
const read = path => fs.readFileSync(path, 'utf8')
const work = read('src/application/work/workService.js')
const location = read('src/application/work/location.js')
const manifest = read('android/app/src/main/AndroidManifest.xml')
const main = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const view = read('src/views/WorkModuleView.vue')
assert.match(location, /getCurrentPosition/)
assert.match(location, /capturedAt/)
assert.match(location, /LocationRepository\.record/)
assert.match(work, /eventType: 'START'/)
assert.match(work, /eventType: 'RIDE_START'/)
assert.match(work, /eventType: 'END'/)
assert.match(work, /setTripRideStartLocation\(data\.id, location, result\.tripStartAt \|\| null\)/)
assert.match(work, /setTripEndLocation\(tripId, location\)/)
assert.match(manifest, /ACCESS_FINE_LOCATION/)
assert.match(manifest, /ACCESS_COARSE_LOCATION/)
assert.doesNotMatch(manifest, /ACCESS_BACKGROUND_LOCATION|FOREGROUND_SERVICE_LOCATION|\.KfeNativeGpsService/)
assert.doesNotMatch(main, /KfeNativeGpsService\.resumePersisted/)
assert.doesNotMatch(view, /nativeGps\.(start|stop|syncTrace)|movementTrace\.(start|reset|resumePersisted|pause)|liveMovementLabel/)
console.log('GPS lifecycle contract: one-shot trip-boundary snapshots only; no active trace collector.')
