import assert from 'node:assert/strict'
import { calculateLoanEmi } from '../domain/math/loan.js'
import { LoanCalculationService } from '../application/admin/loanCalculationService.js'
assert.equal(calculateLoanEmi({ principal: 120000, tenureMonths: 12, annualInterestRatePercent: 0 }), 10000)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 12, annualInterestRatePercent: 12 }), 8884.88)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 24, annualInterestRatePercent: 12 }), 4707.35)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 0, annualInterestRatePercent: 12 }), null)
assert.equal(calculateLoanEmi({ principal: 0, tenureMonths: 12, annualInterestRatePercent: 12 }), null)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 12, annualInterestRatePercent: -1 }), null)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 12, annualInterestRatePercent: '' }), null)
assert.equal(calculateLoanEmi({ principal: 100000, tenureMonths: 12, annualInterestRatePercent: null }), null)
const terms = { principal: 100000, tenureMonths: 12, annualInterestRatePercent: 12, startDate: '2025-01-01', firstEmiDueDate: '2025-01-15' }
assert.equal(LoanCalculationService.monthlyEmi({ principal: 120000, tenureMonths: 12, annualInterestRatePercent: 0 }), 10000)
assert.equal(LoanCalculationService.roundedPaymentAmount({ principal: 127000, tenureMonths: 12, annualInterestRatePercent: 12 }), 11284)
const schedule = LoanCalculationService.schedule(terms)
assert.equal(schedule.length, 12)
assert.equal(schedule[0].dueDate, '2025-01-15')
assert.equal(schedule[0].openingBalance, 100000)
assert.ok(schedule[0].interest > 0)
assert.equal(schedule.at(-1).closingBalance, 0)
const preview = LoanCalculationService.previewPrepayment(terms, [], { amount: 10000, paymentDate: '2025-01-10' })
assert.equal(preview.amount, 10000)
assert.equal(preview.outstandingBefore, 100000)
assert.equal(preview.outstandingAfter, 90000)
assert.ok(preview.interestSaved > 0)
assert.ok(preview.monthsReduced > 0)
assert.equal(preview.emiAmount, LoanCalculationService.monthlyEmi(terms))
const postPrepaymentSchedule = LoanCalculationService.scheduleWithTransactions(terms, [{ id: 'prepay-1', type: 'PREPAYMENT', amount: 10000, paymentDate: '2025-01-10' }])
assert.equal(postPrepaymentSchedule[0].openingBalance, 90000)
assert.ok(postPrepaymentSchedule.length < schedule.length, 'Prepayment with unchanged EMI must shorten the projected schedule.')
assert.ok(postPrepaymentSchedule.at(-1).closingBalance <= 0.01)
const source = (await import('node:fs')).readFileSync('src/views/AdminView.vue', 'utf8')
const panel = (await import('node:fs')).readFileSync('src/components/admin/LoanManagementPanel.vue', 'utf8')
const backup = (await import('node:fs')).readFileSync('src/application/backup/backupService.js', 'utf8')
assert.match(source, /LoanManagementPanel/)
assert.match(panel, /Payment date/)
assert.match(panel, /Confirm and record prepayment/)
assert.match(panel, /Payment records/)
assert.match(backup, /loan_transactions/)
console.log('Loan repayment contract: PASS — EMI rounding, dated schedule, payment history surface and reduced-tenure prepayment preview.')
