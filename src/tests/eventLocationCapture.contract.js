import assert from 'node:assert/strict'
import fs from 'node:fs'

const workService = fs.readFileSync('src/application/work/workService.js', 'utf8')
const locationRepository = fs.readFileSync('src/repositories/locationRepository.js', 'utf8')
const eventLocationService = fs.readFileSync('src/application/location/eventLocationService.js', 'utf8')
const boundary = fs.readFileSync('src/application/work/tripBoundaryLocation.js', 'utf8')
const domainBoundary = fs.readFileSync('src/domain/location/tripBoundaryLocation.js', 'utf8')
const locationAdapter = fs.readFileSync('src/infrastructure/android/tripBoundaryLocationAdapter.js', 'utf8')
const runtimePorts = fs.readFileSync('src/application/work/workRuntimePorts.js', 'utf8')
const nativePlugin = fs.readFileSync('android/app/src/main/java/com/kanishka/pwa/KfeTripBoundaryLocationPlugin.java', 'utf8')
const nativeOverlay = fs.readFileSync('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java', 'utf8')
const nativeGpsPolicy = fs.readFileSync('android/app/src/main/java/com/kanishka/pwa/KfeGpsEventPolicy.java', 'utf8')
const journal = fs.readFileSync('android/app/src/main/java/com/kanishka/pwa/KfeGpsEventJournal.java', 'utf8')

for (const event of ['PICKUP_START', 'TRIP_CANCELLED', 'TRIP_START', 'TRIP_END']) {
  assert.ok(eventLocationService.includes(`'${event}'`))
  assert.ok(nativePlugin.includes(`"${event}".equals(eventType)`))
  assert.ok(workService.includes("captureAndPersistEventLocation('TRIP'"))
}
assert.match(workService, /captureAndPersistEventLocation\('TRIP', result\.id, 'PICKUP_START'/)
assert.match(workService, /captureAndPersistEventLocation\('TRIP', result\.id, 'TRIP_START'/)
assert.match(workService, /captureAndPersistEventLocation\('TRIP', data\?\.id, 'TRIP_END'/)
assert.match(workService, /captureAndPersistEventLocation\('TRIP', data\?\.id, 'TRIP_CANCELLED'/)
assert.doesNotMatch(workService, /captureAndPersistEventLocation\('(SHIFT|FUEL)'/)
assert.match(eventLocationService, /EventLocalityService\.resolveSnapshot\(snapshot\)/)
assert.match(eventLocationService, /resolveNativeSnapshotAfterCapture/)
assert.match(eventLocationService, /CanonicalWorkBoundary\.getEventLocationSnapshot/)
assert.match(locationRepository, /GPS snapshot requires the location provider fix timestamp/)
assert.match(locationRepository, /capturedAt: new Date\(fixTimestamp\)\.toISOString\(\)/)
assert.match(eventLocationService, /LocationRepository\.record\(/)
assert.match(eventLocationService, /CanonicalWorkBoundary\.persistEventLocationSnapshot/)
assert.match(locationAdapter, /maximumAge: 0/)
assert.match(locationAdapter, /\[0, 3000, 7000, 12000, 20000, 27000\]/)
assert.match(locationAdapter, /30000 - \(Date\.now\(\) - startedAt\)/)
assert.match(runtimePorts, /tripBoundaryLocation: \['queueEventLocationCapture', 'captureOneShotLocation'\]/)
assert.match(domainBoundary, /accuracy !== null && \(!Number\.isFinite\(accuracy\) \|\| accuracy < 0\)/)
assert.match(boundary, /domain\/location\/tripBoundaryLocation\.js/)
assert.doesNotMatch(boundary, /captureCurrentLocation/)
assert.match(nativeOverlay, /manager\.requestLocationUpdates\(provider,3000L,0f/)
assert.match(nativeOverlay, /handler\.postDelayed\(stop,30000L\)/)
assert.match(nativeOverlay, /accuracy>75f/)
assert.match(nativeOverlay, /!Double\.isFinite\(accuracy\)\|\|accuracy<0d\|\|accuracy>75d/)
assert.match(nativeOverlay, /removeUpdates\(this\)/)
assert.match(nativeOverlay, /queueEventLocationCapture\(Context context,String entityType,String entityId,String eventType,String eventAt\)/)
assert.ok(nativeOverlay.includes('KfeGpsEventPolicy.snapshotId(entityType,entityId,eventType)'))
assert.match(journal, /RETRY_DELAYS_MS = \{30_000L, 60_000L, 2\*60_000L/)
assert.doesNotMatch(nativeOverlay, /schedulePendingGpsRetry/)
assert.match(nativeOverlay, /later event, app-open, or explicit status refresh/)
assert.ok(nativeGpsPolicy.includes('TRIP_END'))
assert.doesNotMatch(nativeGpsPolicy, /SHIFT_START|SHIFT_END/)
assert.match(nativePlugin, /backgroundCaptureAllowed/)
assert.match(nativeOverlay, /isEventGpsFixAtOrAfter\(eventAt,fixTime\)/)
assert.match(nativeOverlay, /isValidPersistedEventGpsSnapshot\(JSONObject snapshot\)/)
console.log('PASS: four event GPS capture uses bounded multi-fix retries and durable pending retry')
