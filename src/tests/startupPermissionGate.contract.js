import assert from 'node:assert/strict'
import fs from 'node:fs'
import { findFirstMissingNativeCheck } from '../application/startup/permissionStartupChecks.js'
const gate=fs.readFileSync('src/application/startup/permissionGate.js','utf8')
const checks=fs.readFileSync('src/application/startup/permissionStartupChecks.js','utf8')
const main=fs.readFileSync('src/main.js','utf8')
const app=fs.readFileSync('src/App.vue','utf8')
const native=fs.readFileSync('android/app/src/main/java/com/kanishka/pwa/KfeNativeGpsPlugin.java','utf8')
const manifest=fs.readFileSync('android/app/src/main/AndroidManifest.xml','utf8')
for(const key of ['location','locationServices','notifications','overlay','oemAutostart','oemBattery']) assert.ok(checks.includes("key: '"+key+"'"),'startup gate checks '+key)
assert.doesNotMatch(checks,/key: 'backgroundLocation'/)
assert.doesNotMatch(manifest,/ACCESS_BACKGROUND_LOCATION|FOREGROUND_SERVICE_LOCATION|\.KfeNativeGpsService/)
assert.match(native,/checkSelfPermission\(getContext\(\), Manifest\.permission\.ACCESS_FINE_LOCATION\)/)
assert.match(native,/locationManager\.isLocationEnabled\(\)/)
assert.match(gate,/await NativeGate\.getStartupPermissionStatus\(\)/)
assert.match(gate,/findFirstMissingNativeCheck/)
assert.match(main,/await runStartupPermissionGate\(\)/)
assert.ok(main.indexOf('await runStartupPermissionGate()')<main.indexOf('StartupService.startApplication()'))
assert.match(app,/permissionGateState\.status !== 'ready'/)
const ready={fineLocationAllowed:true,locationServicesEnabled:true,notificationsAllowed:true,overlayAllowed:true,oemBackgroundSettingsRequired:true}
const oem=new Set(['oemAutostart','oemBattery'])
assert.equal(findFirstMissingNativeCheck(ready,oem),null)
assert.equal(findFirstMissingNativeCheck({...ready,fineLocationAllowed:false},oem)?.key,'location')
assert.equal(findFirstMissingNativeCheck({...ready,locationServicesEnabled:false},oem)?.key,'locationServices')
console.log('Startup permission gate contract: foreground one-shot location only.')
