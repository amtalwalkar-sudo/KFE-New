import assert from 'node:assert/strict'
import fs from 'node:fs'

const main = fs.readFileSync('src/main.js', 'utf8')
const startup = fs.readFileSync('src/application/startup/startupService.js', 'utf8')
const platform = fs.readFileSync('src/infrastructure/startup/platformStartup.js', 'utf8')
const sw = fs.readFileSync('public/service-worker.js', 'utf8')
const manifest = JSON.parse(fs.readFileSync('public/manifest.json', 'utf8'))
const index = fs.readFileSync('index.html', 'utf8')
const vite = fs.readFileSync('vite.config.js', 'utf8')

assert.equal((main.match(/serviceWorker\.register\s*\(/g) || []).length, 0, 'main.js must not own service-worker registration')
assert.equal((platform.match(/serviceWorker\.register\s*\(/g) || []).length, 1, 'PlatformStartup must own the single registration path')
assert.match(startup, /await platform\.initializeStorage\(\)/, 'storage initialization remains explicit and recoverable')
assert.match(startup, /await MutationRepository\.recoverStaleSyncing\(\)/, 'stale canonical mutations remain explicitly recovered')
assert.match(startup, /void platform\.registerServiceWorker\(\)/, 'service-worker registration must remain non-blocking')
const serviceWorkerRegistration = startup.indexOf('void platform.registerServiceWorker()')
const storageInitialization = startup.indexOf('await platform.initializeStorage()')
assert.ok(serviceWorkerRegistration >= 0 && serviceWorkerRegistration < storageInitialization, 'service-worker registration must start before storage recovery')
assert.match(platform, /const base = getWebAppBase\(\)/)
assert.match(platform, /serviceWorker\.register\(\`\$\{base\}service-worker\.js\`, \{ scope: base, updateViaCache: 'none' \}\)/)
assert.match(platform, /window\.location\.pathname\.startsWith\('\/KFE-New\/'\)/)
assert.match(platform, /registration\.update\(\)\.catch/)

assert.match(sw, /const CACHE_NAME = 'kfe-pwa-shell-__KFE_BUILD_ID__'/)
assert.match(sw, /cache\.addAll\(SHELL_ASSETS\)/)
assert.match(sw, /request\.mode === 'navigate'/)
assert.match(sw, /return new Response\('', \{ status: 504/)
assert.match(sw, /self\.clients\.claim\(\)/)
assert.match(sw, /self\.skipWaiting\(\)/)

assert.equal(manifest.start_url, './')
assert.equal(manifest.scope, './')
assert.equal(manifest.display, 'standalone')
assert.equal(manifest.orientation, 'portrait')
assert.match(index, /<link rel="manifest" href="\.\/manifest\.json"/)
assert.doesNotMatch(index, /BOOT_TIMEOUT_MS/)
assert.doesNotMatch(index, /KFE is taking longer than expected/)
assert.doesNotMatch(index, /window\.setTimeout/)
assert.doesNotMatch(index, /window\.addEventListener\(['"](?:error|unhandledrejection)/)
assert.match(main, /app\.mount\('#app'\)/)
assert.match(main, /window\.__KFE_APP_MOUNTED__ = true/)
assert.match(main, /window\.dispatchEvent\(new CustomEvent\('kfe:app-mounted'\)/)
assert.match(main, /import\('\.\/application\/startup\/startupService\.js'\)/)
assert.match(main, /void StartupService\.startApplication\(\)\.catch/)
assert.doesNotMatch(main, /startupRuntime/)
assert.match(startup, /export const startApplication/)
assert.match(startup, /export const resetStartupAttempt/)
assert.match(startup, /export \{ startupState \}/)
assert.equal(fs.existsSync('src/application/startup/startupRuntime.js'), false, 'startupRuntime.js must be retired; StartupService is the sole startup authority')
assert.match(vite, /base:\s*['"]\.\/['"]/)
assert.ok(fs.existsSync('tools/stamp-service-worker.mjs'), 'production build must stamp the service-worker cache identity')

console.log('Phase 3 startup/PWA lifecycle contract passed: one StartupService authority, no competing boot watchdog.')
