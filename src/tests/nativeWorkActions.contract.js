import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = path => fs.readFileSync(path, 'utf8')
const exists = path => fs.existsSync(path)

const manifest = read('android/app/src/main/AndroidManifest.xml')
const mainActivity = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const gpsService = read('android/app/src/main/java/com/kanishka/pwa/KfeNativeGpsService.java')
const overlayService = read('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java')
const actionsPlugin = read('android/app/src/main/java/com/kanishka/pwa/KfeNativeWorkActionsPlugin.java')
const gpsPlugin = read('android/app/src/main/java/com/kanishka/pwa/KfeNativeGpsPlugin.java')
const workView = read('src/views/WorkModuleView.vue')
const adminView = read('src/views/AdminView.vue')
const workPorts = read('src/application/work/workRuntimePorts.js')
const workAdapter = read('src/infrastructure/work/workRuntimeAdapter.js')
const actionService = read('src/infrastructure/android/nativeWorkActions.js')
const overlayLifecycle = read('src/infrastructure/android/androidOverlayLifecycle.js')
const packageJson = read('package.json')
const gradle = read('android/app/build.gradle')
const capacitorBuildGradle = read('android/app/capacitor.build.gradle')
const capacitorSettings = read('android/capacitor.settings.gradle')

// The ride-notification feature is deleted, not stubbed or disabled.
assert.equal(exists('android/app/src/main/java/com/kanishka/pwa/KfeRideNotificationsPlugin.java'), false)
assert.equal(exists('android/app/src/main/java/com/kanishka/pwa/KfeRideNotificationReceiver.java'), false)
assert.equal(exists('src/infrastructure/android/kfeRideNotificationService.js'), false)
assert.doesNotMatch(manifest, /KfeRideNotificationReceiver/)
assert.doesNotMatch(mainActivity, /KfeRideNotificationsPlugin/)
assert.doesNotMatch(workView, /rideNotifications|KfeRideNotificationService|rideNotificationAction|notificationPhase/)
assert.doesNotMatch(workPorts, /rideNotifications/)
assert.doesNotMatch(workAdapter, /KfeRideNotificationService|rideNotifications/)
assert.doesNotMatch(adminView, /KfeRideNotificationService|chooseNotifications|Control KFE ride and system action notifications/)
assert.doesNotMatch(packageJson, /@capacitor\/local-notifications/)
assert.doesNotMatch(gradle, /capacitor-local-notifications/)
assert.doesNotMatch(capacitorBuildGradle, /capacitor-local-notifications/)
assert.doesNotMatch(capacitorSettings, /capacitor-local-notifications/)

// Android foreground-service notices remain, separate from Work actions.
assert.match(manifest, /android\.permission\.FOREGROUND_SERVICE/)
assert.match(manifest, /android\.permission\.FOREGROUND_SERVICE_LOCATION/)
assert.match(manifest, /android\.permission\.FOREGROUND_SERVICE_SPECIAL_USE/)
assert.match(manifest, /android\.permission\.POST_NOTIFICATIONS/)
assert.match(gpsService, /private static final int NOTIFICATION_ID = 7110/)
assert.match(gpsService, /startForeground\(/)
assert.match(overlayService, /startForeground\(NOTIFICATION_ID,buildNotification\(\)\)/)
assert.match(overlayService, /KFE driver controls are active in the background/)
assert.doesNotMatch(overlayService, /GOING TO PICKUP|PICKUP IN PROGRESS|TRIP ACTIVE|TRIP COMPLETED|gpsIndicator|Dead KM|Trips/)

// Overlay actions retain their own durable bridge and do not route through notifications.
assert.match(mainActivity, /registerPlugin\(KfeNativeWorkActionsPlugin\.class\)/)
assert.match(overlayService, /KfeNativeWorkActionsPlugin\.recordPendingAction/)
assert.match(overlayService, /KfeNativeWorkActionsPlugin\.emitAction/)
assert.doesNotMatch(overlayService, /KfeRideNotificationsPlugin|cancelNotification/)
assert.match(actionsPlugin, /KfeNativeEventStore\.get\(getContext\(\)\)\.pending\(100\)/)
assert.match(actionsPlugin, /KfeNativeEventStore\.get\(getContext\(\)\)\.acknowledge\(eventId\)/)
assert.match(actionsPlugin, /notifyListeners\("nativeWorkAction"/)
assert.match(actionsPlugin, /kfe_native_work_actions/)
assert.match(actionsPlugin, /deleteNotificationChannel\("kfe_ride_actions"\)/)
assert.match(actionService, /registerPlugin\('KfeNativeWorkActions'\)/)
assert.match(workView, /WorkRuntimePorts\.nativeWorkActions\.addListener/)
assert.match(workView, /WorkRuntimePorts\.nativeWorkActions\.consumePendingActions/)
assert.match(workView, /WorkRuntimePorts\.nativeWorkActions\.acknowledgeAction/)
assert.doesNotMatch(overlayLifecycle, /notificationPhase/)
assert.doesNotMatch(gpsPlugin, /kfe_ride_actions/)

console.log('KFE native Work action separation contract: PASS')
