import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const overlay = read('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java')
const store = read('android/app/src/main/java/com/kanishka/pwa/KfeCanonicalWorkStore.java')
const pwa = read('src/views/WorkModuleView.vue')
const workActions = read('src/infrastructure/android/nativeWorkActions.js')
const androidGate = read('tools/android-exact-apk-smoke-gate.sh')
const nativeAcceptance = read('android/app/src/androidTest/java/com/kanishka/pwa/KfeNativeFullShiftAcceptanceTest.java')

assert.ok(overlay.includes('private void persistCanonicalTripForm(String mode,String tripId,JSONObject input,String eventId)'), 'Canonical form persistence must accept the durable event ID')
assert.match(overlay, /native-form-\"\+mode\+\"-\"\+eventId/)
assert.match(overlay, /canonical\.putRecord\(operationId,\"TRIP\",trip\)/)
assert.match(overlay, /trip\.put\(\"status\",\"COMPLETED\"\)/)
assert.match(overlay, /trip\.put\(\"status\",\"CANCELLED\"\)/)
assert.match(overlay, /trip\.put\(\"fareDetailsSkipped\"/)
assert.match(overlay, /trip\.put\(\"cancelReason\"/)
assert.match(overlay, /finishNativeFormCommit\(\)/)
assert.match(store, /operationId was already used for a different command/)
assert.ok(overlay.includes('!trip.optString("deletedAt","").trim().isEmpty()||trip.optBoolean("deleted",false)'), 'Native revenue projection excludes soft-deleted trips like PWA calculation')
assert.ok(overlay.includes('revenueValue.trim().isEmpty()?0d:Double.parseDouble(revenueValue)'), 'Blank native cancellation fee persists as numeric zero')
assert.ok(overlay.includes('trip.put("cancelledRevenue",cancellationFee)'), 'Native cancellation fee persists in canonical cancellation field')

const fareBranch = overlay.slice(overlay.indexOf('if("FARE".equals(formMode)){', overlay.indexOf('private void submitNumericForm')), overlay.indexOf('}else if("CANCEL".equals(formMode)){', overlay.indexOf('private void submitNumericForm')))
const cancelBranch = overlay.slice(overlay.indexOf('}else if("CANCEL".equals(formMode)){', overlay.indexOf('private void submitNumericForm')), overlay.indexOf('\n  }\n\n  private void persistCanonicalTripForm', overlay.indexOf('private void submitNumericForm')))
assert.ok(fareBranch.indexOf('persistCanonicalTripForm("FARE"') >= 0)
assert.ok(fareBranch.indexOf('recordPendingAction') < fareBranch.indexOf('persistCanonicalTripForm("FARE"'), 'Durable fare event must exist before canonical commit')
assert.ok(cancelBranch.indexOf('persistCanonicalTripForm("CANCEL"') >= 0)
assert.ok(cancelBranch.indexOf('recordPendingAction') < cancelBranch.indexOf('persistCanonicalTripForm("CANCEL"'), 'Durable cancellation event must exist before canonical commit')
assert.doesNotMatch(fareBranch + cancelBranch, /new Intent\(this,\s*MainActivity\.class\)|startActivity\(/, 'Native form submit must not launch the main activity')

assert.match(pwa, /if \(stage === 'CANCEL_RIDE'\)/)
assert.match(pwa, /if \(stage === 'ENTER_FARE' && event\?\.input != null\)/)
assert.match(pwa, /acknowledgeAction\(/)
assert.match(pwa, /CanonicalWorkBoundary\.putRecord\(/)
assert.match(pwa, /operationId: operationId \|\| CanonicalWorkBoundary\.createOperationId\(\)/)
assert.match(pwa, /saveFare\(true, String\(event\?\.eventId \|\| ''\)\)/)
assert.match(pwa, /saveCancel\(true, String\(event\?\.eventId \|\| ''\)\)/)
assert.match(workActions, /getPendingActions\(\)/)
assert.match(workActions, /acknowledgeAction\(\{ eventId, stage, tripId \}\)/)

assert.match(androidGate, /KfeNativeFullShiftAcceptanceTest#nativeOnlyShiftPersistsMultipleFaresAndCancellationAcrossStoreReopen native-full-shift 1/, 'The release smoke gate must execute the native-only full-shift instrumentation test.')
assert.match(androidGate, /KfeNativeFullShiftAcceptanceTest#reopeningPwaCatchesUpNativeCanonicalRecordsWithoutReplayingPendingEvents native-pwa-catch-up 1/, 'The release smoke gate must verify PWA catch-up from canonical native records independently of queued event replay.')
assert.match(nativeAcceptance, /nativeOnlyShiftPersistsMultipleFaresAndCancellationAcrossStoreReopen/, 'Android instrumentation must exercise multiple native-only trips, fare submissions, cancellation and store reopen.')
assert.match(nativeAcceptance, /KfeNativeEventStore\.get\(context\)\.pending\(100\)/, 'The test must verify that unacknowledged native events remain durable without PWA replay.')
assert.match(nativeAcceptance, /Revenue must include both fares and the recorded cancellation fee/, 'The test must verify canonical revenue projection across fare and cancellation submissions.')
console.log('PASS: native overlay fare/cancellation canonical commit and replay contract')
