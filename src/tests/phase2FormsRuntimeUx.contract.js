import fs from 'node:fs'
import assert from 'node:assert/strict'
const root=new URL('../',import.meta.url)
const read=p=>fs.readFileSync(new URL(p,root),'utf8')
const form=read('components/admin/AdminRecordForm.vue')
const admin=read('views/AdminView.vue')
const rules=read('application/admin/universalFormRules.js')
const universal=read('presentation/forms/universalFormSystem.js')
const workForm=read('components/work/WorkContextForm.vue')
const adminForm=read('components/admin/AdminRecordForm.vue')
const fuelForm=read('components/CngFuelModal.vue')
const reconciliationForm=read('components/ShiftReconciliationModal.vue')
const field=read('components/KfeFormField.vue')
assert.ok(universal.includes('.work-context-form'),'Universal input system must own Work contextual forms')
assert.ok(universal.includes('visualViewport'),'Universal input system must respond to virtual keyboard viewport changes')
assert.ok(universal.includes('enterKeyHint'),'Universal input system must provide native Enter/Next/Done hints')
assert.ok(universal.includes('primary-action'),'Universal input system must complete non-form contextual actions')
assert.ok(!workForm.includes('function nextField('),'Work must not maintain a competing keyboard navigation implementation')
assert.ok(!adminForm.includes('function handleEnter('),'Admin must not maintain a competing keyboard navigation implementation')
assert.ok(workForm.includes('@submit.prevent="submitForm"'),'Work contextual states must use native form submission')
assert.ok(!workForm.includes('document.querySelector'), 'Work form state must not read DOM controls as state')
assert.ok(fuelForm.includes('<form id="fuel-log-form"'),'Fuel modal must use a native form surface')
assert.ok(reconciliationForm.includes('<form class="reconcile-card"'),'Reconciliation must use a native form surface')
assert.ok(field.includes('enterkeyhint'),'Shared form field must expose native Enter/Next/Done hints')
assert.ok(form.includes('optionValue(option)'),'Admin native form must support value/label select options')
assert.ok(form.includes('optionLabel(option)'),'Admin native form must render human-readable select labels')
assert.match(form, /busy: \{ type: Boolean, default: false \}/, 'Admin native form must expose a busy state')
assert.ok(form.includes("{{ busy ? 'Saving…' : submitLabel }}"),'Admin native form must communicate save progress')
assert.ok(!form.includes('v-model='),'Admin form must not use Vue-controlled v-model inputs')
assert.ok(form.includes('function onInput(field)'),'Admin fields must write directly through native input events')
assert.ok(form.includes('autocapitalize="off"'),'Admin text entry must not force capitalization')
assert.ok(!form.includes('openEditor') && !form.includes('editorRef') && !form.includes('readonly'),'Admin fields must be directly editable with no popup editor')
assert.ok(form.includes('focusNext(field)'),'Admin form must support keyboard next-field navigation')
assert.ok(form.includes("emit('submit', values)"),'Admin form must submit the complete draft')
assert.ok(admin.includes(':busy="saving"'),'Admin form must lock controls while save is in flight')
assert.ok(admin.includes("label('vehicle',x)"),'Vehicle relationship options must be human-readable')
assert.ok(admin.includes("label('driver',x)"),'Driver relationship options must be human-readable')
assert.ok(admin.includes("label('loan',x)"),'Loan relationship options must be human-readable')
assert.ok(rules.includes("optionValue=option=>"),'Validation must support object select options')
assert.ok(rules.includes("['true','1','yes','on']"),'Checkbox normalization must not treat string false as true')
