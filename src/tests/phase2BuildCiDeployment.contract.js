import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'

const workflow = readFileSync('.github/workflows/consolidated-baseline.yml', 'utf8')
const androidSmokeGate = readFileSync('tools/android-exact-apk-smoke-gate.sh', 'utf8')
const packageJson = JSON.parse(readFileSync('package.json', 'utf8'))

assert.equal(packageJson.type, 'module', 'package must explicitly declare ESM for contract/test scripts')
assert.match(packageJson.scripts?.build || '', /^vite build && node tools\/stamp-service-worker\.mjs$/, 'production build must stamp the service-worker cache identity after Vite build')
assert.equal(packageJson.scripts?.test, 'node src/tests/runAllContracts.js', 'contract runner must remain canonical')
assert.ok(existsSync('package-lock.json'), 'package lockfile must be committed')
assert.ok(existsSync('vite.config.js'), 'Vite configuration must exist')
assert.ok(existsSync('capacitor.config.json'), 'Capacitor configuration must exist')
assert.ok(existsSync('.github/workflows/consolidated-baseline.yml'), 'canonical CI workflow must exist')

assert.match(workflow, /uses:\s+actions\/checkout@v5/, 'CI must use checkout v5')
assert.match(workflow, /uses:\s+actions\/setup-java@v5/, 'CI must use setup-java v5')
assert.match(workflow, /uses:\s+actions\/setup-node@v5/, 'CI must use setup-node v5')
assert.match(workflow, /node-version:\s+22/, 'CI Node version must remain 22')
assert.match(workflow, /cache:\s+gradle/, 'Gradle dependency caching must be enabled')
assert.match(workflow, /cache:\s+npm/, 'npm dependency caching must be enabled')
assert.match(workflow, /npm ci/, 'CI must use lockfile-enforcing npm ci')
assert.match(workflow, /npx cap sync android/, 'CI must verify Capacitor synchronization')
assert.match(workflow, /\.\/gradlew assembleDebug/, 'CI must verify Android debug compilation')
assert.match(workflow, /actions\/upload-pages-artifact@v4/, 'canonical CI must package Pages artifact')
assert.match(workflow, /actions\/deploy-pages@v4/, 'canonical CI must deploy Pages')
assert.match(workflow, /github\.ref == 'refs\/heads\/main' && \(github\.event_name == 'push' \|\| github\.event_name == 'workflow_dispatch'\)/, 'Pages deployment must be restricted to main pushes or explicit main workflow dispatches')
assert.match(workflow, /enable_first_run_setup:/, 'launch setup must be explicitly selectable at workflow dispatch')
assert.match(workflow, /VITE_ENABLE_FIRST_RUN_SETUP:/, 'first-run setup must be controlled by a build-time launch flag')
assert.match(workflow, /android-release-gate:/, 'canonical CI must retain the Android emulator gate')
assert.match(workflow, /needs: detect-changes\s+if: needs\.detect-changes\.outputs\.android_changed == 'true'/, 'Android release verification must run when native/build/workflow impact is detected')
assert.match(workflow, /if: needs\.detect-changes\.outputs\.app_changed == 'true'/, 'application suite must run for app-impacting changes')
assert.match(workflow, /docs-policy-check|Documentation policy check|docs_only/, 'CI must retain a lightweight documentation-only validation path')
assert.match(workflow, /needs: \[detect-changes, build-and-test\]/, 'deployment must depend on change classification and successful app validation')
assert.ok(!existsSync('.github/workflows/deploy-pages.yml'), 'duplicate Pages deployment workflow must remain removed')
assert.match(androidSmokeGate, /trap cleanup_background_jobs EXIT/, 'Android smoke gate must clean up background helpers on every exit path')
assert.match(androidSmokeGate, /kill "\$GPS_FEED_PID"/, 'Android smoke gate must stop the GPS feeder after instrumentation failures')
assert.match(androidSmokeGate, /timeout 180s adb shell am instrument/, 'Android instrumentation must have a hard timeout')


console.log('Phase 2 build/CI/deployment contract passed')
