import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const read = path => readFile(new URL(path, import.meta.url), 'utf8')
const router = await read('../router/index.js')
const adminView = await read('../views/AdminView.vue')
const settingsView = await read('../views/AdminSettingsOnlyView.vue')
const settingsService = await read('../application/admin/persistentSettingsService.js')
const settingsRepository = await read('../repositories/persistentSettingsRepository.js')
const backupRepository = await read('../repositories/backupRepository.js')
const settingsUi = await read('../components/KfeSettingsView.vue')

assert.match(router, /path: '\/timeline', name: 'Timeline', component: ActivityTimelineView/)
assert.match(router, /path: '\/performance', name: 'Performance', component: PerformanceView/)
assert.match(router, /path: '\/', name: 'Work', component: WorkModuleView/)
assert.match(router, /path: '\/admin', name: 'Admin', component: AdminView/)
assert.match(adminView, /<AdminSourceForm/, 'The active Admin route must expose the existing reusable source-record form')
assert.match(adminView, /const items=\[/, 'The active Admin route must own the existing Admin menu inventory')
assert.match(adminView, /settingsOpen/, 'The active Admin view must retain its settings entry point')
assert.match(settingsView, /<KfeSettingsView :application="application"\s*\/>/)
assert.match(settingsService, /complianceDefaults: 'complianceDefaults'/)
assert.match(settingsService, /emiDefaults: 'emiDefaults'/)
assert.match(settingsService, /PersistentSettingsRepository\.save\(key, values\)/)
assert.doesNotMatch(settingsService, /utils\/indexedDB\.js/)
assert.match(settingsRepository, /initializeCanonicalStorage\(\)/)
assert.match(settingsRepository, /objectStore\('settings'\)\.put\(record\)/)
assert.match(backupRepository, /resetStores = \[\.\.\.new Set\(\[\.\.\.stores, 'form_drafts', 'canonical_operations'\]\)\]/)
assert.match(backupRepository, /'form_drafts'/)
assert.match(settingsUi, /settings\/preferences will return to factory defaults/i)
assert.match(settingsUi, /recovery checkpoint will be retained/i)
assert.doesNotMatch(settingsUi, /Saved configuration defaults will remain|Saved settings and defaults are retained/)
assert.match(settingsUi, /Reset business data/)
console.log('Admin route wiring and persistent settings contract: PASS')
