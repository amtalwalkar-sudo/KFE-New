import assert from 'node:assert/strict'
import fs from 'node:fs'
const work = fs.readFileSync('src/application/work/workService.js', 'utf8')
const location = fs.readFileSync('src/application/work/location.js', 'utf8')
const repository = fs.readFileSync('src/repositories/shiftTripRepository.js', 'utf8')
const completed = work.slice(work.indexOf('async completeTrip'), work.indexOf('async cancelTrip'))
assert.match(location, /getCurrentPosition/)
assert.match(location, /capturedAt/)
assert.match(location, /LocationRepository\.record/)
assert.match(completed, /eventType: 'END'/)
assert.match(completed, /setTripEndLocation\(tripId, location\)/)
assert.doesNotMatch(completed, /MovementReconciliationService|routeTrace|nativeGps\.syncTrace|enrichTripMovement/)
assert.match(repository, /async setTripEndLocation/)
assert.match(repository, /tripEndLocationStatus/)
console.log('Saved-trip endpoint contract: fresh one-shot GPS snapshot only; no route or trace enrichment.')
