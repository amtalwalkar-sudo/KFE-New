import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = path => fs.readFileSync(path, 'utf8')
const location = read('src/application/work/location.js')
const work = read('src/application/work/workService.js')
const view = read('src/views/WorkModuleView.vue')
const manifest = read('android/app/src/main/AndroidManifest.xml')
const main = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const permissionChecks = read('src/application/startup/permissionStartupChecks.js')
const startup = read('src/application/startup/startupService.js')
const queue = read('src/application/work/movementReconciliationQueue.js')
const nativeOverlay = read('android/app/src/main/java/com/kanishka/pwa/KfeOverlayService.java')

assert.match(location, /navigator\.geolocation\.getCurrentPosition/)
assert.match(location, /const capturedAt = new Date\(position\.timestamp \|\| Date\.now\(\)\)\.toISOString\(\)/)
assert.match(location, /LocationRepository\.record/)
assert.doesNotMatch(location, /watchPosition/, 'Lifecycle snapshot capture must be one-shot, not a recurring GPS watch.')
assert.match(work, /eventType: 'START'/, 'Trip creation captures its start snapshot.')
assert.match(work, /eventType: 'RIDE_START'/, 'Start Trip captures a fresh passenger-ride boundary.')
assert.match(work, /eventType: 'END'/, 'End Trip captures a fresh endpoint snapshot.')
assert.match(work, /setTripEndLocation\(tripId, location\)/)
const completion = work.slice(work.indexOf('async completeTrip'), work.indexOf('async cancelTrip'))
assert.doesNotMatch(completion, /nativeGps\.(start|stop|syncTrace)|routeTrace\(|enrichTripMovement/)
const endShift = work.slice(work.indexOf('async endShift'), work.indexOf('async recordFuel'))
assert.doesNotMatch(endShift, /reconcileShiftMovement|createRouter|syncTrace|nativeGps\.listTraceOwners/)
assert.doesNotMatch(view, /MovementReconciliationQueue|nativeGps\.(start|stop|syncTrace)|movementTrace\.(start|reset|resumePersisted|pause)|liveMovementLabel|pendingFareGpsGap|LIVE GPS ESTIMATE|BUSINESS KM|DEAD KM/)
assert.doesNotMatch(view, /\/offline-maps|Offline Maps/)
assert.match(manifest, /android\.permission\.ACCESS_FINE_LOCATION/)
assert.match(manifest, /android\.permission\.ACCESS_COARSE_LOCATION/)
assert.doesNotMatch(manifest, /ACCESS_BACKGROUND_LOCATION|FOREGROUND_SERVICE_LOCATION|\.KfeNativeGpsService/)
assert.match(main, /registerPlugin\(KfeNativeGpsPlugin\.class\)/, 'The native plugin remains for foreground location permission status.')
assert.match(nativeOverlay, /captureOneShotTripBoundary\(pendingTripId, "tripStartLocation"\)/)
assert.match(nativeOverlay, /captureOneShotTripBoundary\(pendingTripId, "rideStartLocation"\)/)
assert.match(nativeOverlay, /captureOneShotTripBoundary\(pendingTripId, "tripEndLocation"\)/)
assert.match(nativeOverlay, /manager\.getCurrentLocation\(LocationManager\.GPS_PROVIDER/)
assert.match(nativeOverlay, /manager\.requestSingleUpdate\(LocationManager\.GPS_PROVIDER/)
assert.match(nativeOverlay, /snapshot\.put\("capturedAt",java\.time\.Instant\.ofEpochMilli\(fixTime\)\.toString\(\)\)/)
assert.doesNotMatch(nativeOverlay, /KfeNativeGpsService\.(start|stop)\(/)
assert.doesNotMatch(main, /KfeNativeGpsService\.resumePersisted/)
assert.doesNotMatch(permissionChecks, /key: 'backgroundLocation'/)
assert.doesNotMatch(startup, /recoverNativeGpsTraces/)
assert.doesNotMatch(queue, /addEventListener\('online'|reconcilePending\(\)\s*$/)
console.log('One-shot offline trip GPS snapshot contract: PASS')
