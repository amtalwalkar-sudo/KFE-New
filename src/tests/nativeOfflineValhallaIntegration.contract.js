import assert from 'node:assert/strict'
import fs from 'node:fs'
const read = path => fs.readFileSync(path, 'utf8')
const activity = read('android/app/src/main/java/com/kanishka/pwa/MainActivity.java')
const router = read('src/router/index.js')
const settings = read('src/components/KfeSettingsView.vue')
const work = read('src/application/work/workService.js')
const view = read('src/views/WorkModuleView.vue')
const bridge = read('src/infrastructure/location/offlineMapService.js')
const routeAdapter = read('src/infrastructure/location/valhallaRoutingAdapter.js')
const backup = read('src/application/backup/backupService.js')
assert.doesNotMatch(activity, /registerPlugin\(KfeOfflineMapsPlugin\.class\)/)
assert.doesNotMatch(router, /OfflineMapsView|\/offline-maps/)
assert.doesNotMatch(settings, /Offline Maps|offline-maps/)
assert.doesNotMatch(view, /MovementReconciliationQueue|routeTrace|liveMovementLabel|LIVE KM|DEAD KM|BUSINESS KM/)
const completedTrip = work.slice(work.indexOf('async completeTrip'), work.indexOf('async cancelTrip'))
const endShift = work.slice(work.indexOf('async endShift'), work.indexOf('async recordFuel'))
assert.doesNotMatch(completedTrip, /routeTrace|createRouter|enrichTripMovement/)
assert.doesNotMatch(endShift, /reconcileShiftMovement|createRouter/)
assert.ok(bridge.includes('KfeOfflineMaps') && routeAdapter.includes('ValhallaRoutingAdapter'), 'Routing implementation is retained in source for later reactivation, but is not wired into the active Work flow.')
assert.doesNotMatch(backup, /offline-maps|valhalla_tiles|routing_tiles|map_files/i)
console.log('Offline Maps / Valhalla contract: architecture retained, active UI and routing disabled.')
