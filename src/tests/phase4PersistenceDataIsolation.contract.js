import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = path => fs.readFileSync(path, 'utf8')
const indexedDB = read('src/utils/indexedDB.js')
const mutations = read('src/repositories/mutationRepository.js')
const adminRepo = read('src/repositories/adminRepository.js')
const backupRepo = read('src/repositories/backupRepository.js')
const backup = read('src/application/backup/backupService.js')

assert.match(indexedDB, /const CANONICAL_DB_NAME = 'kanishka_kfe_canonical_db'/)
assert.ok(indexedDB.includes("import { CANONICAL_DB_VERSION, RETIRED_CANONICAL_STORES } from '../constants/canonicalDatabase.js'"), 'Canonical IndexedDB must import the single database version and retired-store inventory.')
assert.match(indexedDB, /indexedDB\.open\(name, CANONICAL_DB_VERSION\)/)
assert.match(indexedDB, /export const initializeCanonicalStorage = async \(\) => initializeDatabase\(CANONICAL_DB_NAME\)/)
assert.match(indexedDB, /export const openCanonicalDB = initializeCanonicalStorage/)
assert.doesNotMatch(indexedDB, /SYNTHETIC_DB_NAME|SYNTHETIC_DB_VERSION|DATA_SOURCE_KEY|setActiveDataSource|getActiveDataSource|initializeSyntheticStorage/)
assert.doesNotMatch(mutations, /getActiveDataSource/)
assert.match(mutations, /mutationStore\.put\(mutation\)/)
assert.match(mutations, /auditStore\.put\(buildAuditRecord/)
assert.match(adminRepo, /ACTIVE_ADMIN_FORM_KEYS/)
assert.match(backupRepo, /openCanonicalDB/)
assert.match(backupRepo, /saveResetCheckpoint/)
assert.match(backup, /CANONICAL_BACKUP_STORES/)
assert.match(backup, /V5_BACKUP_STORES/)
assert.match(backup, /financial_period_snapshots/)
assert.match(backup, /loan_payments/)
assert.match(backup, /new Set\(RETIRED_CANONICAL_STORES\)/)
assert.doesNotMatch(backup.slice(backup.indexOf('export const CANONICAL_BACKUP_STORES'), backup.indexOf('// Format 5')), /financial_period_snapshots|loan_payments/)
console.log('Persistence isolation contract: one canonical database; legacy backups validate, but retired stores are excluded from current restore data.')
